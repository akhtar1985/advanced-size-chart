export function statusBadge(billing) {
  if (!billing) return '<span class="badge">Checking plan…</span>';
  if (billing.status === 'active') return '<span class="badge badge-success"><span class="dot"></span>Subscription active</span>';
  if (billing.status === 'trial') {
    return `<span class="badge badge-accent"><span class="dot"></span>Trial · ${billing.daysRemaining} ${plural(billing.daysRemaining, 'day')} left</span>`;
  }
  if (billing.status === 'none') return '<span class="badge badge-critical"><span class="dot"></span>Subscription required</span>';
  return '<span class="badge badge-warning"><span class="dot"></span>Plan status unknown</span>';
}

export function download(filename, content, type) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
